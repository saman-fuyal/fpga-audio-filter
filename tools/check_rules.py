#!/usr/bin/env python3
"""Static check of the project's RTL coding rules (run on every change).

    python tools/check_rules.py          (exit code 0 = all rules hold)

Rules
  R1  synthesizable logic only: no `initial`, no `#delay`, no $display/$readmem/$finish,
      no `wait`, `forever`, `while`, `repeat` in rtl/ (for-loops with constant bounds are fine).
  R2  no latches: every combinational block starts by assigning defaults or every `case`
      has a `default:` branch; Yosys is also asked to prove there is no latch ($dlatch).
  R3  sequential blocks use only <=, combinational blocks use only = .
  R4  every module has the section banners: ports, (localparams|wires|registers),
      combinational, sequential (generated ROMs and pure-structural modules excepted).
  V   Verilog-2001 for Vivado 2018.2: no SystemVerilog keywords in rtl/*.v.
"""
import glob, os, re, subprocess, sys

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))
FILES = sorted(glob.glob(os.path.join(ROOT, "rtl", "*.v")))
errors = []


def strip_comments(txt):
    txt = re.sub(r"/\*.*?\*/", lambda m: "\n" * m.group(0).count("\n"), txt, flags=re.S)
    return re.sub(r"//[^\n]*", "", txt)


def blocks(code, kind):
    """Yield (line, body) of every `always @(posedge ...)` or `always @(*)` block."""
    pat = r"always\s*@\s*\(\s*posedge[^)]*\)" if kind == "seq" else r"always\s*@\s*\(\s*\*\s*\)"
    for m in re.finditer(pat, code):
        i = m.end()
        line = code[:m.start()].count("\n") + 1
        rest = code[i:].lstrip()
        if rest.startswith("begin"):
            depth, j = 0, i + code[i:].index("begin")
            for t in re.finditer(r"\b(begin|end)\b", code[j:]):
                depth += 1 if t.group(1) == "begin" else -1
                if depth == 0:
                    yield line, code[j:j + t.end()]
                    break
        else:
            yield line, rest.split(";", 1)[0] + ";"


SV_WORDS = r"\b(logic|always_ff|always_comb|always_latch|int|bit|byte|typedef|enum|struct|automatic|unique|priority|interface|modport|import|package)\b"

for f in FILES:
    name = os.path.relpath(f, ROOT)
    raw = open(f).read()
    code = strip_comments(raw)
    generated = "GENERATED by" in raw
    # R1
    for pat, what in [(r"\binitial\b", "initial block"), (r"#\s*\d", "#delay"),
                      (r"\$(display|readmem[hb]|finish|stop|write|monitor|fopen|random)", "simulation task"),
                      (r"\b(wait|forever|while|repeat)\b", "non-synthesizable loop")]:
        for m in re.finditer(pat, code):
            # `timescale 1ns/1ps is a directive, not a delay
            if what == "#delay" and code[max(0, m.start() - 20):m.start()].strip().endswith("parameter"):
                continue
            ln = code[:m.start()].count("\n") + 1
            if what == "#delay" and re.match(r"\s*`timescale", raw.splitlines()[ln - 1]):
                continue
            if what == "#delay" and re.search(r"#\s*\(", code[m.start():m.start() + 3]):
                continue
            errors.append(f"R1 {name}:{ln}: {what}")
    # V
    for m in re.finditer(SV_WORDS, code):
        ln = code[:m.start()].count("\n") + 1
        errors.append(f"V  {name}:{ln}: SystemVerilog keyword '{m.group(1)}'")
    if re.search(r"'[01xz]\b(?!\w)", code.replace("1'b", "").replace("'d", "")) and re.search(r"[=(,\s]'[01]\s*[;,)]", code):
        errors.append(f"V  {name}: SystemVerilog fill literal ('0 / '1)")
    # R3
    for ln, body in blocks(code, "seq"):
        for m in re.finditer(r"(?<![<>=!])=(?!=)", body):
            seg = body[max(0, m.start() - 40):m.start()]
            if re.search(r"\bfor\s*\([^;]*$", seg) or re.search(r";\s*\w+\s*$", seg) and "for" in seg:
                continue  # loop variable in a for header
            errors.append(f"R3 {name}:{ln}: blocking '=' inside sequential block")
            break
    for ln, body in blocks(code, "comb"):
        if "<=" in re.sub(r"\(([^()]*<=[^()]*)\)", "", body) and re.search(r"\w\s*<=\s*[^=]", body.replace("(", " ").replace(")", " ")):
            # allow comparisons a <= b inside conditions
            for stmt in re.split(r";", body):
                s = stmt.strip()
                if re.match(r"^[\w\[\]:+\-*\s{}.,`']+<=", s) and not re.match(r"^(if|else|case|for)\b", s):
                    errors.append(f"R3 {name}:{ln}: non-blocking '<=' inside combinational block")
                    break
    # R2: each comb block must either have a default for every case, or start with defaults
    for ln, body in blocks(code, "comb"):
        ncase = len(re.findall(r"\bcase[xz]?\s*\(", body))
        ndef = len(re.findall(r"\bdefault\s*:", body))
        if ncase > ndef:
            errors.append(f"R2 {name}:{ln}: case without default")
    # R4
    if not generated:
        low = raw.lower()
        need = ["ports", "combinational", "sequential"]
        if "module" in low and not all(k in low for k in need):
            miss = [k for k in need if k not in low]
            errors.append(f"R4 {name}: missing section banner(s): {', '.join(miss)}")

# R2 proof with Yosys: no latch cells after proc
try:
    ys = ("read_verilog -I{0}/rtl {1}; hierarchy -top top_nexys_a7; proc; opt_clean; "
          "select -assert-none t:$dlatch t:$adlatch t:$dlatchsr; "
          "select -assert-none t:$sr t:$aldff").format(ROOT, " ".join(FILES))
    p = subprocess.run(["yosys", "-q", "-p", ys], capture_output=True, text=True, cwd=ROOT)
    if p.returncode:
        errors.append("R2 yosys: latch or async element found:\n" + p.stdout[-1500:] + p.stderr[-1500:])
    else:
        print("yosys: no latches, no asynchronous set/reset elements")
except FileNotFoundError:
    print("yosys not found - latch proof skipped")

for e in errors:
    print(e)
print(f"{len(FILES)} files checked, {len(errors)} rule violation(s)")
sys.exit(1 if errors else 0)
