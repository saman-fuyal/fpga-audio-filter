#!/usr/bin/env python3
"""Project 3: coefficients, golden model and test vectors for the ASIC FIR core.

The FPGA design uses a 511-tap time-multiplexed FIR (one DSP slice + RAM). An ASIC built
with the open SKY130 flow has no hard multipliers and no RAM macro in the default flow, so
the ASIC version is a *parallel* linear-phase FIR with constant coefficients:

    31 taps, symmetric -> 16 pre-adders, 16 constant multipliers, 16-input adder tree
    16-bit data (Q1.15), 16-bit coefficients (Q1.15), round + saturate to 16 bits

Two micro-architectures are generated from the same RTL (parameter PIPE):
    PIPE=0  one register stage at the output  -> long combinational path, fewer flops
    PIPE=1  registers after pre-add, multiply and every adder-tree level -> short path

Outputs: rtl/fir_par_coefs.vh, mem/coef_par.hex, asic/vectors/*.hex, asic/results/asic_fir.json
"""
import json, os
import numpy as np
from scipy import signal

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT_RTL = os.path.join(HERE, "..", "rtl")   # fir_par.v lives in rtl/, shared by FPGA and ASIC
NTAPS, DW, CW, CFRAC = 31, 16, 16, 15
FS = 50_000


def wrap(v, w):
    m = 1 << w; v &= m - 1
    return v - m if v >= (m >> 1) else v


def sat(v, w):
    lo, hi = -(1 << (w - 1)), (1 << (w - 1)) - 1
    return lo if v < lo else hi if v > hi else v


def design():
    # telephone-band anti-alias low-pass: pass 0-3.4 kHz, stop >= 7 kHz at fs = 50 kHz
    h = signal.remez(NTAPS, [0, 3400, 7000, FS / 2], [1, 0], weight=[1, 10], fs=FS)
    q = np.round(h * (1 << CFRAC)).astype(int)
    assert np.all(q == q[::-1])
    return h, q


def fir_model(x, q):
    """y[n] = sat16(round(sum q[k] x[n-k] / 2^15)), history starts at 0.
    Latency is handled by the testbench (it aligns on out_valid)."""
    hist = [0] * NTAPS
    out = []
    for v in x:
        hist = [v] + hist[:-1]
        acc = sum(int(c) * int(s) for c, s in zip(q, hist))
        out.append(sat((acc + (1 << (CFRAC - 1))) >> CFRAC, DW))
    return out


def csd_digits(c):
    """Number of non-zero canonical-signed-digit terms (adders per constant multiplier)."""
    c = abs(int(c)); n = 0
    while c:
        if c & 1:
            n += 1
            c = c - 1 if (c & 3) == 1 else c + 1
        c >>= 1
    return n


def main():
    h, q = design()
    os.makedirs(os.path.join(HERE, "vectors"), exist_ok=True)
    os.makedirs(os.path.join(HERE, "results"), exist_ok=True)
    half = (NTAPS + 1) // 2
    with open(os.path.join(ROOT_RTL, "fir_par_coefs.vh"), "w") as fh:
        fh.write("// GENERATED by asic/design_asic_fir.py -- do not edit\n")
        fh.write(f"// {NTAPS}-tap symmetric low-pass, Q1.{CFRAC}.\n")
        fh.write("// coef(i) multiplies the pair of taps at distance i from the centre tap.\n")
        fh.write("// Included inside module fir_par (rtl/fir_par.v).\n")
        fh.write(f"function signed [{CW - 1}:0] coef;\n    input [4:0] i;\n    begin\n        case (i)\n")
        for i, v in enumerate(q[:half][::-1]):
            lit = f"{CW}'sd{v}" if v >= 0 else f"-{CW}'sd{-v}"
            fh.write(f"            5'd{i}: coef = {lit};\n")
        fh.write(f"            default: coef = {CW}'sd0;\n        endcase\n    end\nendfunction\n")
    # full coefficient list for the Python golden model (model/golden.py, bank 4)
    with open(os.path.join(HERE, "..", "mem", "coef_par.hex"), "w") as fh:
        fh.write("\n".join(format(int(v) & 0xFFFF, "04X") for v in q) + "\n")
    rng = np.random.default_rng(7)
    lo, hi = -(1 << (DW - 1)), (1 << (DW - 1)) - 1
    x = [hi] + [0] * 40 + list(rng.integers(lo, hi + 1, 1500)) + \
        [hi if c >= 0 else lo for c in q[::-1]] + [0] * 40 + \
        list((0.8 * hi * np.sin(2 * np.pi * 1000 * np.arange(500) / FS)).astype(int))
    y = fir_model(x, q)
    for name, vals in (("x.hex", x), ("y.hex", y)):
        with open(os.path.join(HERE, "vectors", name), "w") as fh:
            fh.write("\n".join(format(v & 0xFFFF, "04X") for v in vals) + "\n")
    w, H = signal.freqz(q / (1 << CFRAC), worN=8192, fs=FS)
    db = 20 * np.log10(np.maximum(np.abs(H), 1e-12))
    res = dict(taps=NTAPS, data_bits=DW, coef_bits=CW,
               passband_ripple_db=float(db[w <= 3400].max() - db[w <= 3400].min()),
               stopband_atten_db=float(-db[w >= 7000].max()),
               unique_multipliers=half,
               csd_nonzero_digits_total=int(sum(csd_digits(c) for c in q[:half])),
               n_vectors=len(x))
    with open(os.path.join(HERE, "results", "asic_fir.json"), "w") as fh:
        json.dump(res, fh, indent=2)
    print(json.dumps(res, indent=2))


if __name__ == "__main__":
    main()
