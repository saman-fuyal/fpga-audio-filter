#!/usr/bin/env python3
"""Design every filter in the chain, quantize it, and emit the RTL ROM files.

Outputs
  mem/coef_comp.hex      63-tap CIC-compensation FIR, 18-bit Q2.16, 64 entries
  mem/coef_main.hex      4 banks x 512 entries, 18-bit Q2.16
  rtl/af_params.vh       `define constants shared with RTL (generated, do not edit)
  rtl/coef_rom_comp.v    synthesizable coefficient ROMs (case statement + output register)
  rtl/coef_rom_main.v
  results/filters.json   achieved specs (passband ripple, stopband attenuation) for the report
  docs/report/figs/*.pdf frequency-response figures
"""
import json, os, sys
import numpy as np
from scipy import signal

sys.path.insert(0, os.path.dirname(__file__))
from params import *  # noqa: F401,F403

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))
FIGS = os.path.join(ROOT, "docs", "report", "figs")


# ------------------------------------------------------------------ CIC response
def cic_mag(f, n=CIC_N, r=CIC_R, fin=F_PDM):
    """Normalized |H(f)| of an N-stage, decimate-by-R CIC (DC gain = 1)."""
    f = np.asarray(f, dtype=float)
    x = np.pi * f / fin
    num = np.sin(r * x)
    den = r * np.sin(x)
    out = np.ones_like(f)
    nz = np.abs(den) > 1e-15
    out[nz] = np.abs(num[nz] / den[nz]) ** n
    return out


# ------------------------------------------------------------------ comp FIR (WLS, type I)
def design_comp(ntaps=COMP_TAPS, fs=F_CIC, fpass=16_000, fstop=25_000, wstop=400.0):
    """Weighted-least-squares linear-phase FIR whose passband is 1/|H_cic|.

    Passband 0..fpass: desired = 1/|H_cic(f)| (droop compensation)
    Stopband fstop..fs/2: desired 0, protects 0..fs/2-fstop after decimation by 2.
    """
    m = (ntaps - 1) // 2
    fp = np.linspace(0, fpass, 800)
    fsb = np.linspace(fstop, fs / 2, 1600)
    f = np.concatenate([fp, fsb])
    d = np.concatenate([1.0 / cic_mag(fp), np.zeros_like(fsb)])
    w = np.concatenate([np.ones_like(fp), wstop * np.ones_like(fsb)])
    k = np.arange(m + 1)
    C = np.cos(2 * np.pi * np.outer(f, k) / fs)
    C[:, 1:] *= 2.0
    sw = np.sqrt(w)
    a, *_ = np.linalg.lstsq(C * sw[:, None], d * sw, rcond=None)
    h = np.concatenate([a[:0:-1], a])  # a[m],...,a[1],a[0],a[1],...,a[m]
    return h


# ------------------------------------------------------------------ main banks
def design_main(ntaps=MAIN_TAPS, fs=FS):
    banks = []
    # 0: bypass = pure delay of (N-1)/2 samples so switching banks keeps alignment
    h0 = np.zeros(ntaps)
    h0[(ntaps - 1) // 2] = 1.0
    banks.append(h0)
    # 1: low-pass, pass 0..1000 Hz, stop >= 1400 Hz
    banks.append(signal.remez(ntaps, [0, 1000, 1400, fs / 2], [1, 0], weight=[1, 30], fs=fs))
    # 2: high-pass, stop 0..1600 Hz, pass >= 2000 Hz
    banks.append(signal.remez(ntaps, [0, 1600, 2000, fs / 2], [0, 1], weight=[30, 1], fs=fs))
    # 3: telephone band-pass 400..3400 Hz (ITU-T G.712-like voice band)
    banks.append(signal.remez(ntaps, [0, 60, 400, 3400, 3800, fs / 2], [0, 1, 0],
                              weight=[30, 1, 30], fs=fs))
    return banks


def coef_shift(h, cw=CW, frac=CFRAC):
    """Largest extra left-shift s so that round(h * 2^(frac+s)) still fits in cw signed bits.

    Narrow-band filters have tiny coefficients; scaling them up uses all 18 bits and the
    accumulator result is shifted back by (frac + s). This recovers ~6 dB of stopband
    attenuation per bit of scaling (quantization-noise floor drops).
    """
    hi = (1 << (cw - 1)) - 1
    s = 0
    while np.max(np.abs(np.round(np.asarray(h) * (1 << (frac + s + 1))))) <= hi:
        s += 1
    return s


def quantize(h, cw=CW, frac=CFRAC):
    q = np.round(np.asarray(h) * (1 << frac)).astype(np.int64)
    lo, hi = -(1 << (cw - 1)), (1 << (cw - 1)) - 1
    if q.min() < lo or q.max() > hi:
        raise ValueError("coefficient overflow")
    return q


def to_hex(vals, width):
    digits = (width + 3) // 4
    mask = (1 << width) - 1
    return [format(int(v) & mask, "0{}X".format(digits)) for v in vals]


def write_rom(name, aw, vals, cw, title):
    """Write a synthesizable ROM: combinational case on the address, registered output.

    No initial block / $readmemh, so the same file works in Vivado (infers a block ROM),
    Yosys, Icarus and Verilator. Unlisted addresses return 0 (explicit default, no latch).
    """
    path = os.path.join(ROOT, "rtl", name + ".v")
    lines = [
        "// GENERATED by model/design_filters.py -- do not edit",
        f"// {title}",
        f"// {len(vals)} entries x {cw} bits, two's complement. Read latency: 1 clock.",
        "`timescale 1ns/1ps",
        "`default_nettype none",
        f"module {name} (",
        "    // ---------------------------------------------------------------- ports",
        "    input  wire                 clk,",
        f"    input  wire [{aw - 1}:0]        addr,",
        f"    output reg  signed [{cw - 1}:0] q",
        ");",
        "    // ---------------------------------------------------------------- wires / regs",
        f"    reg signed [{cw - 1}:0] rom_d;",
        "",
        "    // ---------------------------------------------------------------- combinational: look-up",
        "    always @(*) begin",
        "        case (addr)",
    ]
    for a, v in enumerate(vals):
        if v != 0:
            lit = f"{cw}'sd{v}" if v >= 0 else f"-{cw}'sd{-v}"
            lines.append(f"            {aw}'d{a}: rom_d = {lit};")
    lines += [
        f"            default: rom_d = {cw}'sd0;",
        "        endcase",
        "    end",
        "",
        "    // ---------------------------------------------------------------- sequential: output register",
        "    always @(posedge clk) begin",
        "        q <= rom_d;",
        "    end",
        "endmodule",
        "`default_nettype wire",
        "",
    ]
    with open(path, "w") as fh:
        fh.write("\n".join(lines))


def response_db(h, fs, n=1 << 16):
    w, H = signal.freqz(h, worN=n, fs=fs)
    return w, 20 * np.log10(np.maximum(np.abs(H), 1e-12))


def band_stats(h, fs, passbands, stopbands):
    w, db = response_db(h, fs)
    out = {}
    if passbands:
        sel = np.zeros_like(w, dtype=bool)
        for a, b in passbands:
            sel |= (w >= a) & (w <= b)
        out["passband_ripple_db"] = float(db[sel].max() - db[sel].min())
    if stopbands:
        sel = np.zeros_like(w, dtype=bool)
        for a, b in stopbands:
            sel |= (w >= a) & (w <= b)
        out["stopband_atten_db"] = float(-db[sel].max())
    return out


def main():
    os.makedirs(os.path.join(ROOT, "mem"), exist_ok=True)
    os.makedirs(os.path.join(ROOT, "results"), exist_ok=True)
    os.makedirs(FIGS, exist_ok=True)
    report = {}

    # ---------------- comp FIR
    hc = design_comp()
    sc = coef_shift(hc)
    qc = quantize(hc, frac=CFRAC + sc)
    hcq = qc / (1 << (CFRAC + sc))
    with open(os.path.join(ROOT, "mem", "coef_comp.hex"), "w") as fh:
        fh.write("\n".join(to_hex(list(qc) + [0] * ((1 << COMP_AW) - COMP_TAPS), CW)) + "\n")
    write_rom("coef_rom_comp", COMP_AW, [int(v) for v in qc], CW,
              f"CIC compensation FIR, {COMP_TAPS} taps, Q2.16 scaled by 2^{sc}")
    # overall CIC+comp response, measured at the 100 kHz rate before decimation
    w, Hc = signal.freqz(hcq, worN=1 << 15, fs=F_CIC)
    tot = 20 * np.log10(np.maximum(np.abs(Hc) * cic_mag(w), 1e-12))
    pb = w <= 16_000
    report["comp"] = {
        "taps": COMP_TAPS,
        "cic_droop_at_16k_db": float(20 * np.log10(cic_mag([16_000])[0])),
        "cic_plus_comp_ripple_0_16k_db": float(tot[pb].max() - tot[pb].min()),
        "cic_plus_comp_ripple_0_20k_db": float(tot[w <= 20_000].max() - tot[w <= 20_000].min()),
        "stopband_25k_50k_atten_db": float(-tot[w >= 25_000].max()),
        "dc_gain": float(np.sum(hcq)),
        "max_abs_coef": int(np.abs(qc).max()),
        "sum_abs_coef": float(np.abs(hcq).sum()),
        "coef_shift": sc,
    }

    # ---------------- main banks
    banks = design_main()
    specs = [
        dict(passbands=[(0, 20_000)], stopbands=[]),
        dict(passbands=[(0, 1000)], stopbands=[(1400, FS / 2)]),
        dict(passbands=[(2000, FS / 2 - 1)], stopbands=[(0, 1600)]),
        dict(passbands=[(400, 3400)], stopbands=[(0, 60), (3800, FS / 2)]),
    ]
    lines = []
    romvals = []
    qbanks = []
    report["main"] = []
    shifts = []
    for b, (h, sp) in enumerate(zip(banks, specs)):
        sb = coef_shift(h)
        shifts.append(sb)
        q = quantize(h, frac=CFRAC + sb)
        qbanks.append(q / (1 << sb))   # back to Q2.16 scale for plotting
        lines += to_hex(list(q) + [0] * ((1 << MAIN_AW) - MAIN_TAPS), CW)
        romvals += [int(v) for v in q] + [0] * ((1 << MAIN_AW) - MAIN_TAPS)
        st_f = band_stats(h, FS, **sp)
        st_q = band_stats(q / (1 << (CFRAC + sb)), FS, **sp)
        st_u = band_stats(quantize(h) / (1 << CFRAC), FS, **sp)
        report["main"].append({
            "bank": b, "name": BANK_NAMES[b], "taps": MAIN_TAPS,
            "float": st_f, "quantized": st_q, "quantized_unscaled": st_u,
            "coef_shift": sb,
            "max_abs_coef": int(np.abs(q).max()),
            "sum_abs_coef": float(np.abs(q).sum() / (1 << (CFRAC + sb))),
            "group_delay_samples": (MAIN_TAPS - 1) // 2,
            "group_delay_ms": 1e3 * ((MAIN_TAPS - 1) // 2) / FS,
        })
    with open(os.path.join(ROOT, "mem", "coef_main.hex"), "w") as fh:
        fh.write("\n".join(lines) + "\n")
    write_rom("coef_rom_main", MAIN_AW + 2, romvals, CW,
              f"main FIR, {MAIN_BANKS} banks x {MAIN_TAPS} taps, address = {{bank[1:0], tap[8:0]}}, "
              f"bank b scaled by 2^s_b, s = {shifts}")

    # ---------------- accumulator headroom proof (worst-case |acc| < 2^(ACC_W-1))
    worst_bits = []
    for sa, sh in [(report["comp"]["sum_abs_coef"], sc)] + [(m["sum_abs_coef"], m["coef_shift"]) for m in report["main"]]:
        worst_bits.append(np.log2(sa * (1 << (DW - 1)) * (1 << (CFRAC + sh))))
    acc_bits = int(np.ceil(max(worst_bits))) + 1
    report["accumulator_bits_needed"] = acc_bits
    assert acc_bits <= ACC_W, "accumulator too small"

    # ---------------- latency budget (cycles at 100 MHz)
    report["cycles_per_audio_sample"] = F_SYS // FS
    report["main_fir_cycles_per_output"] = MAIN_TAPS + 6
    report["comp_fir_cycles_per_output"] = COMP_TAPS + 6
    report["end_to_end_group_delay_ms"] = 1e3 * (
        (CIC_N * (CIC_R - 1) / 2) / F_PDM + ((COMP_TAPS - 1) / 2) / F_CIC + ((MAIN_TAPS - 1) / 2) / FS)

    with open(os.path.join(ROOT, "results", "filters.json"), "w") as fh:
        json.dump(report, fh, indent=2)

    # ---------------- generated Verilog header
    vh = f"""// GENERATED by model/design_filters.py from model/params.py -- do not edit
`ifndef AF_PARAMS_VH
`define AF_PARAMS_VH
`define AF_F_SYS       {F_SYS}
`define AF_MCLK_DIV    {MCLK_DIV}
`define AF_SAMPLE_HI   {SAMPLE_CNT_HI}
`define AF_SAMPLE_LO   {SAMPLE_CNT_LO}
`define AF_CIC_N       {CIC_N}
`define AF_CIC_R       {CIC_R}
`define AF_CIC_W       {CIC_W}
`define AF_CIC_SHIFT   {CIC_SHIFT}
`define AF_COMP_TAPS   {COMP_TAPS}
`define AF_COMP_AW     {COMP_AW}
`define AF_COMP_DECIM  {COMP_DECIM}
`define AF_COMP_SHIFT  {sc}
`define AF_MAIN_TAPS   {MAIN_TAPS}
`define AF_MAIN_AW     {MAIN_AW}
`define AF_MAIN_BANKS  {MAIN_BANKS}
// per-bank extra coefficient scaling, 4 bits each, bank 0 in the LSBs
`define AF_MAIN_SHIFTS 16'h{''.join(format(x, 'X') for x in shifts[::-1])}
`define AF_DW          {DW}
`define AF_CW          {CW}
`define AF_CFRAC       {CFRAC}
`define AF_ACC_W       {ACC_W}
`define AF_DC_K        {DC_K}
`define AF_OUT_W       {OUT_W}
`define AF_PWM_BITS    {PWM_BITS}
`define AF_BAUD        {BAUD}
`define AF_CAP_AW      {CAP_AW}
`define AF_VER_MAJOR   {VERSION[0]}
`define AF_VER_MINOR   {VERSION[1]}
`endif
"""
    with open(os.path.join(ROOT, "rtl", "af_params.vh"), "w") as fh:
        fh.write(vh)

    report["main_shifts"] = shifts
    with open(os.path.join(ROOT, "results", "filters.json"), "w") as fh:
        json.dump(report, fh, indent=2)
    make_plots(hcq, qbanks)
    print(json.dumps(report, indent=2))


def savefig(fig, name):
    """Every figure as vector PDF (LaTeX) and 600-dpi PNG (Word)."""
    fig.savefig(os.path.join(FIGS, name + ".pdf"))
    fig.savefig(os.path.join(FIGS, name + ".png"), dpi=600)


# Plots are in colour (colour-blind-safe Okabe-Ito palette) and keep distinct line styles, so they
# still read in a greyscale print. Block and flow diagrams (figs_src/*.tex) stay black on white.
C_BLUE, C_VERM, C_GREEN, C_ORANGE, C_PURPLE, C_SKY = "#0072B2", "#D55E00", "#009E73", "#E69F00", "#CC79A7", "#56B4E9"


def bw_style():
    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt
    plt.rcParams.update({"font.size": 8, "font.family": "STIXGeneral", "mathtext.fontset": "stix",
                         "axes.grid": True, "grid.color": "#bbbbbb", "grid.linewidth": 0.4,
                         "lines.linewidth": 1.0, "axes.edgecolor": "black", "axes.linewidth": 0.6,
                         "legend.frameon": True, "legend.edgecolor": "black", "legend.fancybox": False})
    return plt


def make_plots(hcq, qbanks):
    plt = bw_style()
    # ---- decimator: CIC alone, comp alone, cascade (at the 100 kHz rate)
    w, Hc = signal.freqz(hcq, worN=1 << 14, fs=F_CIC)
    fig, ax = plt.subplots(figsize=(3.5, 2.3))
    ax.plot(w / 1e3, 20 * np.log10(cic_mag(w)), ":", color=C_BLUE, lw=1.2, label="CIC ($N$=4, $R$=25)")
    ax.plot(w / 1e3, 20 * np.log10(np.maximum(np.abs(Hc), 1e-9)), "--", color=C_VERM, lw=0.9, label="Comp. FIR (63 taps)")
    ax.plot(w / 1e3, 20 * np.log10(np.maximum(np.abs(Hc) * cic_mag(w), 1e-9)), "-", color="black", lw=1.0, label="Cascade")
    ax.axvspan(25, 50, facecolor="#fdf1e6", edgecolor="#f3c99a", hatch="///", lw=0, zorder=0)
    ax.set_xlim(0, 50); ax.set_ylim(-110, 10)
    ax.set_xlabel("Frequency (kHz)"); ax.set_ylabel("Magnitude (dB)")
    ax.legend(loc="lower left", fontsize=6.5)
    fig.tight_layout(); savefig(fig, "decimator_response"); plt.close(fig)

    # ---- passband zoom of the droop compensation
    fig, ax = plt.subplots(figsize=(3.5, 1.9))
    pb = w <= 22_000
    ax.plot(w[pb] / 1e3, 20 * np.log10(cic_mag(w[pb])), ":", color=C_BLUE, lw=1.2, label="CIC droop")
    ax.plot(w[pb] / 1e3, 20 * np.log10(np.abs(Hc[pb]) * cic_mag(w[pb])), "-", color=C_GREEN, label="CIC + comp.")
    ax.axvline(16, color="#666666", lw=0.5, ls="-.")
    ax.set_xlabel("Frequency (kHz)"); ax.set_ylabel("Magnitude (dB)")
    ax.legend(fontsize=6.5); fig.tight_layout(); savefig(fig, "droop_comp"); plt.close(fig)

    # ---- filter banks 1-3 (quantized, scaled) and the 31-tap ASIC core (bank 4)
    styles = [None, ("-", 1.0, C_BLUE), ("--", 1.0, C_VERM), ("-.", 1.0, C_GREEN)]
    fig, ax = plt.subplots(figsize=(3.5, 2.4))
    for b, q in enumerate(qbanks):
        if b == 0:
            continue
        wf, db = response_db(q / (1 << CFRAC), FS)
        ax.semilogx(np.maximum(wf, 1), db, styles[b][0], lw=styles[b][1], color=styles[b][2], label=f"{b}: {BANK_NAMES[b]}")
    par_path = os.path.join(ROOT, "mem", "coef_par.hex")
    if os.path.exists(par_path):
        qp = [int(l, 16) - (1 << 16) if int(l, 16) >= (1 << 15) else int(l, 16) for l in open(par_path) if l.strip()]
        wf, db = response_db(np.array(qp) / (1 << 15), FS)
        ax.semilogx(np.maximum(wf, 1), db, ":", color=C_PURPLE, lw=1.4, label="4: 31-tap ASIC core")
    ax.set_xlim(20, 25_000); ax.set_ylim(-110, 8)
    ax.set_xlabel("Frequency (Hz)"); ax.set_ylabel("Magnitude (dB)")
    ax.legend(fontsize=6, loc="upper center", bbox_to_anchor=(0.5, -0.24), ncol=2, frameon=False)
    fig.set_size_inches(3.5, 2.75); fig.tight_layout()
    savefig(fig, "main_banks"); plt.close(fig)


if __name__ == "__main__":
    main()
